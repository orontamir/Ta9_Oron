<#
.SYNOPSIS
  Creates the API keys of this installation in .env (once), and loads them into the current PowerShell session.
  The keys are random, per installation, and never committed (.env is in .gitignore).
.EXAMPLE
  ./scripts/keys.ps1             # create .env if it does not exist (docker compose reads it automatically)
  ./scripts/keys.ps1 -Force      # replace the keys (restart the services afterwards)
  . ./scripts/keys.ps1           # dot-source: also sets Auth__* for "dotnet run" in this session
  ./scripts/keys.ps1 -Show       # print the client keys (for Swagger "Authorize" or Postman)
#>
param([switch]$Force, [switch]$Show)

$ErrorActionPreference = "Stop"
$envFile = Join-Path (Split-Path -Parent $PSScriptRoot) ".env"

function New-ApiKey {
    $bytes = New-Object byte[] 32
    $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

if ($Force -or -not (Test-Path $envFile)) {
    @(
        "# API keys of this installation. Generated by scripts/keys.ps1. Never commit this file."
        "TA9_READER_KEY=$(New-ApiKey)"
        "TA9_OPERATOR_KEY=$(New-ApiKey)"
        "TA9_JOB_SERVICE_KEY=$(New-ApiKey)"
        "TA9_PROCESSOR_SERVICE_KEY=$(New-ApiKey)"
    ) | Set-Content -Path $envFile -Encoding ascii
    Write-Host "Created $envFile with new API keys."
}

$keys = @{}
Get-Content $envFile | Where-Object { $_ -match '^\s*(TA9_[A-Z_]+)\s*=\s*(\S+)\s*$' } | ForEach-Object { $keys[$Matches[1]] = $Matches[2] }

# Variables for "dotnet run" (ASP.NET Core configuration) and for the smoke-test scripts.
$env:Auth__ReaderKey = $keys.TA9_READER_KEY
$env:Auth__OperatorKey = $keys.TA9_OPERATOR_KEY
$env:Auth__JobServiceKey = $keys.TA9_JOB_SERVICE_KEY
$env:Auth__ProcessorServiceKey = $keys.TA9_PROCESSOR_SERVICE_KEY
$env:TA9_OPERATOR_KEY = $keys.TA9_OPERATOR_KEY
$env:TA9_READER_KEY = $keys.TA9_READER_KEY

if ($Show) {
    Write-Host "Reader key   (read only):   $($keys.TA9_READER_KEY)"
    Write-Host "Operator key (full access): $($keys.TA9_OPERATOR_KEY)"
}
