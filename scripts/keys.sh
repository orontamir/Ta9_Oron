#!/usr/bin/env bash
# Creates the API keys of this installation in .env (once) and exports them.
# The keys are random, per installation, and never committed (.env is in .gitignore).
#   ./scripts/keys.sh            create .env if it does not exist (docker compose reads it automatically)
#   ./scripts/keys.sh --force    replace the keys (restart the services afterwards)
#   source scripts/keys.sh       also exports Auth__* for "dotnet run" in this shell
#   ./scripts/keys.sh --show     print the client keys (for Swagger "Authorize" or Postman)
env_file="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env"
new_key() { head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'; }

if [[ " $* " == *" --force "* || ! -f "$env_file" ]]; then
  {
    echo "# API keys of this installation. Generated by scripts/keys.sh. Never commit this file."
    echo "TA9_READER_KEY=$(new_key)"
    echo "TA9_OPERATOR_KEY=$(new_key)"
    echo "TA9_JOB_SERVICE_KEY=$(new_key)"
    echo "TA9_PROCESSOR_SERVICE_KEY=$(new_key)"
  } > "$env_file"
  chmod 600 "$env_file"
  echo "Created $env_file with new API keys."
fi

set -a
# shellcheck disable=SC1090
. "$env_file"
set +a
export Auth__ReaderKey="$TA9_READER_KEY" Auth__OperatorKey="$TA9_OPERATOR_KEY" \
       Auth__JobServiceKey="$TA9_JOB_SERVICE_KEY" Auth__ProcessorServiceKey="$TA9_PROCESSOR_SERVICE_KEY"

if [[ " $* " == *" --show "* ]]; then
  echo "Reader key   (read only):   $TA9_READER_KEY"
  echo "Operator key (full access): $TA9_OPERATOR_KEY"
fi
