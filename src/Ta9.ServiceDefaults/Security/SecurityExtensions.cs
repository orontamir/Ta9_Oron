using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Builder;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Options;
using Microsoft.OpenApi.Models;

namespace Ta9.ServiceDefaults.Security;

public static class SecurityExtensions
{
    /// <summary>
    /// API-key authentication with role-based policies. <paramref name="accepted"/> lists the only callers this
    /// service trusts. Every endpoint requires a valid key unless it is explicitly anonymous (health checks).
    /// </summary>
    public static WebApplicationBuilder AddApiKeyAuthentication(this WebApplicationBuilder builder, params Caller[] accepted)
    {
        builder.Services.AddOptions<ApiKeyOptions>().Bind(builder.Configuration.GetSection(ApiKeyOptions.SectionName));
        builder.Services.AddSingleton(sp => new ApiKeyRegistry(sp.GetRequiredService<IOptions<ApiKeyOptions>>().Value, accepted));
        builder.Services
            .AddAuthentication(ApiKeyAuthenticationHandler.SchemeName)
            .AddScheme<AuthenticationSchemeOptions, ApiKeyAuthenticationHandler>(ApiKeyAuthenticationHandler.SchemeName, _ => { });
        builder.Services.AddAuthorizationBuilder()
            .AddPolicy(AuthPolicies.Read, policy => policy.RequireRole(Roles.Reader, Roles.Operator))
            .AddPolicy(AuthPolicies.Write, policy => policy.RequireRole(Roles.Operator))
            .AddPolicy(AuthPolicies.Service, policy => policy.RequireRole(Roles.Service))
            // Secure by default: an endpoint without an explicit policy still needs a valid key.
            .SetFallbackPolicy(new AuthorizationPolicyBuilder().RequireAuthenticatedUser().Build());
        builder.Services.AddHostedService<ApiKeyStartupCheck>();
        return builder;
    }

    /// <summary>Sends this service's own key (selected from <see cref="ApiKeyOptions"/>) on every request of the client.</summary>
    public static IHttpClientBuilder AddApiKey(this IHttpClientBuilder builder, Func<ApiKeyOptions, string?> select) =>
        builder.AddHttpMessageHandler(sp =>
        {
            var options = sp.GetRequiredService<IOptions<ApiKeyOptions>>();
            return new ApiKeyHeaderHandler(() => select(options.Value));
        });

    /// <summary>Swagger with an "Authorize" button for the <c>X-Api-Key</c> header.</summary>
    public static IServiceCollection AddSwaggerWithApiKey(this IServiceCollection services) =>
        services.AddSwaggerGen(swagger =>
        {
            swagger.AddSecurityDefinition(ApiKeyAuthenticationHandler.SchemeName, new OpenApiSecurityScheme
            {
                Type = SecuritySchemeType.ApiKey,
                In = ParameterLocation.Header,
                Name = ApiKeyAuthenticationHandler.HeaderName,
                Description = "API key generated by scripts/keys.ps1 (see the Installation Guide)."
            });
            swagger.AddSecurityRequirement(new OpenApiSecurityRequirement
            {
                [new OpenApiSecurityScheme
                {
                    Reference = new OpenApiReference { Type = ReferenceType.SecurityScheme, Id = ApiKeyAuthenticationHandler.SchemeName }
                }] = Array.Empty<string>()
            });
        });
}
